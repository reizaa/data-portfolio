"""Regenerate every dataset, run all six projects, and copy charts for the web page."""
from pathlib import Path
import os, shutil, subprocess, sys

ROOT = Path(__file__).resolve().parent
STEPS = [
    "data/generate.py",
    "projects/01_client_data_cleaning/clean_and_assign.py",
    "projects/02_retention_cohort/analysis.py",
    "projects/03_query_optimization/benchmark.py",
    "projects/04_daily_change_alert/alert.py",
    "projects/05_lead_reengagement/funnel.py",
    "projects/06_feedback_classification/classify.py",
]
for s in STEPS:
    print(f"\n=== {s}")
    subprocess.run([sys.executable, str(ROOT / s)], check=True,
                   env={**os.environ, "PYTHONIOENCODING": "utf-8"})

img = ROOT / "docs" / "img"; img.mkdir(parents=True, exist_ok=True)
for png in (ROOT / "projects").glob("*/output/*.png"):
    shutil.copy(png, img / png.name)

# Bundle every project's web.json into docs/data.js (works from file:// and GitHub Pages).
import json
import pandas as pd

bundle = {p.parent.parent.name[:2]: json.loads(p.read_text(encoding="utf-8"))
          for p in sorted((ROOT / "projects").glob("*/output/web.json"))}

# Data profile per project: what each dummy dataset looks like.
DATASETS = {
    "01": ("Ruang Kerja, a fictional coworking space", ["coworking_payments_raw.csv", "account_managers.csv"], "paid_on", None),
    "02": ("Leafy, a fictional online plant shop", ["plant_shop_orders.csv"], "order_date", None),
    "03": ("Fictional weather-sensor network", ["weather_stations.csv"], None,
           "plus 3,000,000 readings generated at run time (station_id, ts, temp_c, humidity), Jan–Jun 2026; not stored in the repo"),
    "04": ("Kopi Senja, a fictional coffee chain", ["coffee_daily_sales.csv"], "date", None),
    "05": ("LinguaPlus, a fictional language school", ["language_school_events.csv"], "event_time", None),
    "06": ("Fictional hotel guest reviews", ["hotel_reviews.csv"], None, None),
}


def describe(col):
    if pd.api.types.is_numeric_dtype(col):
        return f"number, {col.min():,.0f} to {col.max():,.0f}"
    u = col.dropna().unique()
    return f"text, {len(u)} values" + (f": {', '.join(map(str, sorted(u)[:5]))}" if len(u) <= 5 else f", e.g. {str(u[0])[:40]}")


for key, (business, files, date_col, extra) in DATASETS.items():
    prof = {"business": business, "files": [], "note": extra}
    for i, f in enumerate(files):
        df = pd.read_csv(ROOT / "data" / f)
        entry = {"file": f"data/{f}", "rows": len(df), "columns": [{"name": c, "desc": describe(df[c])} for c in df.columns]}
        if date_col and i == 0:
            d = pd.to_datetime(df[date_col], format="mixed", dayfirst=True)
            entry["period"] = f"{d.min():%d %b %Y} to {d.max():%d %b %Y}"
        prof["files"].append(entry)
    bundle.setdefault(key, {})["profile"] = prof
(ROOT / "docs" / "data.js").write_text(
    "// Generated by run_all.py from synthetic data. Do not edit.\nwindow.PORTFOLIO = "
    + json.dumps(bundle, ensure_ascii=False) + ";\n", encoding="utf-8")
print("\nDone. Open docs/index.html in a browser.")
